    @Test
    void loginRequiresTheStoredPasswordAndSelectedRoleAndCreatesAServerSession() throws Exception {
        register("adopter", "ana@example.test", "0712345678", PASSWORD).andExpect(status().isCreated());
        mvc.perform(get("/api/auth/session"))
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.code").value("NO_SESSION"));

        var wrongPassword = login("adopter", "ana@example.test", "wrong-password")
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.code").value("INVALID_CREDENTIALS")).andReturn();
        assertThat(wrongPassword.getRequest().getSession(false)).isNull();
        login("shelter", "ana@example.test", PASSWORD)
                .andExpect(status().isUnauthorized())
                .andExpect(jsonPath("$.code").value("INVALID_CREDENTIALS"));

        var authenticated = login("adopter", " AnA@Example.test ", PASSWORD)
                .andExpect(status().isOk())
                .andExpect(header().string("Cache-Control", "no-store"))
                .andExpect(jsonPath("$.role").value("adopter"))
                .andExpect(jsonPath("$.firstName").value("Ana"))
                .andExpect(jsonPath("$.password").doesNotExist())
                .andReturn();
        var session = (MockHttpSession) authenticated.getRequest().getSession(false);
        assertThat(session).isNotNull();
        mvc.perform(get("/api/auth/session").session(session))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.email").value("ana@example.test"));
    }

    @Test
    void doesNotStartASessionForPendingSheltersAndAllowsLoginAfterApproval() throws Exception {
        registerShelter("shelter@example.test", "0712345678", "12345678").andExpect(status().isCreated());
        login("shelter", "shelter@example.test", "wrong-password").andExpect(status().isUnauthorized());
        var pending = login("shelter", "shelter@example.test", PASSWORD)
                .andExpect(status().isForbidden())
                .andExpect(jsonPath("$.code").value("SHELTER_APPROVAL_PENDING")).andReturn();
        assertThat(pending.getRequest().getSession(false)).isNull();

        var captor = ArgumentCaptor.forClass(SimpleMailMessage.class);
        verify(mailSender).send(captor.capture());
        String token = captor.getValue().getText().lines().filter(line -> line.contains("?token="))
                .map(line -> URI.create(line).getQuery().substring("token=".length())).findFirst().orElseThrow();
        approve(token).andExpect(status().isOk());
        login("shelter", "shelter@example.test", PASSWORD)
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.role").value("shelter"))
                .andExpect(jsonPath("$.shelterName").value("Centru Test"));
    }

    @Test
    void favoriteWritesRequireAnActiveAdopterSessionAndItsCsrfToken() throws Exception {
        register("adopter", "ana@example.test", "0712345678", PASSWORD).andExpect(status().isCreated());
        var signedIn = login("adopter", "ana@example.test", PASSWORD).andExpect(status().isOk()).andReturn();
        var adopter = (MockHttpSession) signedIn.getRequest().getSession(false);
        String csrfToken = mvc.perform(get("/api/auth/session").session(adopter))
                .andExpect(status().isOk())
                .andExpect(header().exists(AccountSessionService.CSRF_HEADER))
                .andReturn().getResponse().getHeader(AccountSessionService.CSRF_HEADER);

        mvc.perform(post("/api/favorites/42"))
                .andExpect(status().isUnauthorized()).andExpect(jsonPath("$.code").value("NO_SESSION"));
        mvc.perform(post("/api/favorites/42").session(adopter))
                .andExpect(status().isForbidden()).andExpect(jsonPath("$.code").value("INVALID_CSRF_TOKEN"));
        mvc.perform(post("/api/favorites/42").session(adopter).header(AccountSessionService.CSRF_HEADER, csrfToken))
                .andExpect(status().isNotFound());

        registerShelter("shelter@example.test", "0723456789", "12345678").andExpect(status().isCreated());
        jdbc.update("UPDATE utilizatori SET status_cont = 'ACTIV' WHERE email = ?", "shelter@example.test");
        var shelterLogin = login("shelter", "shelter@example.test", PASSWORD).andExpect(status().isOk()).andReturn();
        var shelter = (MockHttpSession) shelterLogin.getRequest().getSession(false);
        mvc.perform(post("/api/favorites/42").session(shelter))
                .andExpect(status().isForbidden()).andExpect(jsonPath("$.code").value("FORBIDDEN"));

        jdbc.update("UPDATE utilizatori SET status_cont = 'IN_ASTEPTARE' WHERE email = ?", "ana@example.test");
        mvc.perform(post("/api/favorites/42").session(adopter).header(AccountSessionService.CSRF_HEADER, csrfToken))
                .andExpect(status().isUnauthorized()).andExpect(jsonPath("$.code").value("NO_SESSION"));
        assertThat(adopter.isInvalid()).isTrue();
    }

