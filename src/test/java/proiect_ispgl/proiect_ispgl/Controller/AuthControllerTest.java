    @Test
    void concurrentShelterRegistrationsWithSameCuiCreateExactlyOneAccount() throws Exception {
        var start = new CyclicBarrier(2);
        try (var executor = Executors.newFixedThreadPool(2)) {
            var first = executor.submit(() -> {
                start.await(10, TimeUnit.SECONDS);
                return registerShelter("first@example.test", "0712345678", "RO 0012345678").andReturn().getResponse();
            });
            var second = executor.submit(() -> {
                start.await(10, TimeUnit.SECONDS);
                return registerShelter("second@example.test", "0723456789", "12345678").andReturn().getResponse();
            });
            var responses = List.of(first.get(15, TimeUnit.SECONDS), second.get(15, TimeUnit.SECONDS));
            assertThat(responses).extracting(response -> response.getStatus()).containsExactlyInAnyOrder(201, 409);
            assertThat(responses.stream().filter(response -> response.getStatus() == 409).findFirst().orElseThrow()
                    .getContentAsString()).contains("CUI_ALREADY_USED");
        }

        assertThat(jdbc.queryForObject("SELECT COUNT(*) FROM utilizatori WHERE cui_cif = ?", Integer.class, "12345678"))
                .isEqualTo(1);
        verify(mailSender).send(any(SimpleMailMessage.class));
    }

    @Test
    void approvalLinkOnlyActivatesTheMatchingPendingShelterOnce() throws Exception {
        registerShelter("shelter@example.test", "0712345678", "12345678").andExpect(status().isCreated());
        var captor = ArgumentCaptor.forClass(SimpleMailMessage.class);
        verify(mailSender).send(captor.capture());
        var email = captor.getValue();
        assertThat(email.getTo()).containsExactly("team@example.test");
        assertThat(email.getFrom()).isEqualTo("no-reply@example.test");
        assertThat(email.getText()).contains("Centru Test", "12345678", "shelter@example.test")
                .doesNotContain(PASSWORD, "$argon2id$");
        var approvalUrl = URI.create(email.getText().lines()
                .filter(line -> line.startsWith("http://localhost:8080")).findFirst().orElseThrow());
        String token = approvalUrl.getQuery().substring("token=".length());
        registerShelter("other@example.test", "0723456789", "87654321").andExpect(status().isCreated());
        long otherAccountId = jdbc.queryForObject("""
                SELECT id_utilizator FROM utilizatori WHERE email = ?
                """, Long.class, "other@example.test");

        mvc.perform(get(approvalUrl))
                .andExpect(status().isOk())
                .andExpect(content().string(containsString("Aprobă centrul")));
        assertThat(accountStatus("shelter@example.test")).isEqualTo("IN_ASTEPTARE");
        approve(otherAccountId + token.substring(token.indexOf('.'))).andExpect(status().isNotFound());
        String incorrectToken = token.substring(0, token.length() - 1) + (token.endsWith("A") ? "B" : "A");
        approve(incorrectToken).andExpect(status().isNotFound());
        assertThat(accountStatus("shelter@example.test")).isEqualTo("IN_ASTEPTARE");

        approve(token).andExpect(status().isOk());
        assertThat(accountStatus("shelter@example.test")).isEqualTo("ACTIV");
        assertThat(accountStatus("other@example.test")).isEqualTo("IN_ASTEPTARE");
        approve(token).andExpect(status().isNotFound());
    }

