    // H2 uses a fixture row to hold a lock until the caller's JDBC transaction ends.
    public static void lockRegistrationCui(Connection connection, int namespace, int key) throws SQLException {
        if (!TransactionSynchronizationManager.isActualTransactionActive()) {
            throw new SQLException("Registration must acquire the CUI lock inside a transaction.");
        }
        try (var statement = connection.prepareStatement("SELECT id FROM registration_test_lock WHERE id = 1 FOR UPDATE");
             var row = statement.executeQuery()) {
            if (!row.next()) throw new SQLException("Registration lock fixture is missing.");
        }
    }

    @Test
    void registrationPersistsActiveAdoptersWithDistinctArgon2idHashes() throws Exception {
        register("adopter", "ANa@Example.test", "0712345678", PASSWORD)
                .andExpect(status().isCreated())
                .andExpect(content().string(""));
        register("adopter", "other@example.test", "0723456789", PASSWORD)
                .andExpect(status().isCreated());

        var first = jdbc.queryForMap("SELECT * FROM utilizatori WHERE email = ?", "ana@example.test");
        assertThat(first.get("prenume")).isEqualTo("Ana");
        assertThat(first.get("nume")).isEqualTo("Test");
        assertThat(first.get("cod_tara")).isEqualTo("+40");
        assertThat(first.get("telefon")).isEqualTo("0712345678");
        assertThat(first.get("tip_utilizator")).isEqualTo("Adoptator");
        assertThat(first.get("status_cont")).isEqualTo("ACTIV");

        String firstHash = (String) first.get("parola_hash");
        String secondHash = jdbc.queryForObject(
                "SELECT parola_hash FROM utilizatori WHERE email = ?", String.class, "other@example.test");
        assertThat(firstHash).startsWith("$argon2id$").isNotEqualTo(PASSWORD);
        assertThat(secondHash).startsWith("$argon2id$").isNotEqualTo(firstHash);
        assertThat(passwordEncoder.matches(PASSWORD, firstHash)).isTrue();
        assertThat(passwordEncoder.matches(PASSWORD, secondHash)).isTrue();
        verifyNoInteractions(mailSender);
    }

